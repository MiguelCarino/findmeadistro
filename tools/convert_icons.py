"""Normalise downloaded icons: 96x96 webp, trimmed and centred on a transparent square.

usage: python3 -I convert_icons.py <download_dir> <out_dir> [skip.txt] [icons.js]
Skips shared hosts (their icon is the host's, not the distro's), tiny icons
(< 32 px: blurry when shown at 56 px) and blank ones. Prints a report.
"""
import sys, os, subprocess, tempfile
from PIL import Image

src, out = sys.argv[1:3]
skip_file = sys.argv[3] if len(sys.argv) > 3 else None
js_file = sys.argv[4] if len(sys.argv) > 4 else None
SKIP = set()
if skip_file:
    SKIP = {l.strip() for l in open(skip_file) if l.strip() and not l.startswith('#')}
os.makedirs(out, exist_ok=True)
SHARED = ('archiveos-org', 'web-archive-org', 'sourceforge-net-projects', 'github-com',
          'sites-google-com', 'emmett31-wixsite-com', 'besgnulinux-blogspot-com')
SIZE = 96
ok, skipped = [], []

for fn in sorted(os.listdir(src)):
    key, _, ext = fn.rpartition('.')
    if fn == 'manifest.tsv':
        continue
    if key in SKIP:
        skipped.append((key, 'in skip list'))
        continue
    if key.startswith(SHARED):
        skipped.append((key, 'shared host'))
        continue
    path = os.path.join(src, fn)
    try:
        if ext == 'svg':
            with tempfile.NamedTemporaryFile(suffix='.png') as t:
                subprocess.run(['rsvg-convert', '-w', '256', '-h', '256', '--keep-aspect-ratio', '-o', t.name, path],
                               check=True, capture_output=True, timeout=20)
                im = Image.open(t.name)
                im.load()
        else:
            im = Image.open(path)
            if ext == 'ico' and hasattr(im, 'ico'):
                im.size = max(im.ico.sizes())
            if getattr(im, 'n_frames', 1) > 1:
                im.seek(0)
            im.load()
    except Exception as e:
        skipped.append((key, 'unreadable: %s' % type(e).__name__))
        continue
    if max(im.size) < 32:
        skipped.append((key, 'too small %dx%d' % im.size))
        continue
    im = im.convert('RGBA')
    box = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
    if not box:
        skipped.append((key, 'blank'))
        continue
    im = im.crop(box)
    lo, hi = zip(*im.convert('RGB').getextrema())
    if max(h - l for l, h in zip(lo, hi)) < 12 and im.getchannel('A').getextrema()[0] > 250:
        skipped.append((key, 'flat colour'))
        continue
    side = max(im.size)
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.width) // 2, (side - im.height) // 2))
    sq = sq.resize((SIZE, SIZE), Image.LANCZOS)
    sq.save(os.path.join(out, key + '.webp'), 'WEBP', quality=90, method=6)
    ok.append(key)

print('converted', len(ok))
for k, why in skipped:
    print('skip', k, '-', why)

# js/icons.js: the keys that have an icon, so the page never asks for one that is missing.
if js_file:
    keys = sorted(f[:-5] for f in os.listdir(out) if f.endswith('.webp'))
    with open(js_file, 'w') as f:
        f.write('// Generated by tools/build_icons.sh: distros with their own icon in img/d/<key>.webp.\n'
                '// key = the card id (host + path), lower-case, runs of other characters as "-".\n'
                'var DISTRO_ICONS = ' + repr(keys).replace("'", '"') + ';\n')
